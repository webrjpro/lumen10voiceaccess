/** Upgrade the existing activity in place and absorb its former local dependency. */
function xmldb_lumen10voiceaccess_upgrade($oldversion): bool {
    if ($oldversion < 2026111001) {
        \mod_lumen10voiceaccess\upgrade_migration::migrate();
        upgrade_mod_savepoint(true, 2026111001, 'lumen10voiceaccess');
    }
    return true;
}
